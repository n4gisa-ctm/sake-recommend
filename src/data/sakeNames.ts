/** プールからランダムに count 件（重複なし・不足時は繰り返し）を返す */
export function pickSakeNames(count: number): string[] {
  const shuffled = [...SAKE_NAMES].sort(() => Math.random() - 0.5);
  const result: string[] = [];
  for (let i = 0; i < count; i++) {
    result.push(shuffled[i % shuffled.length]);
  }
  return result;
}
